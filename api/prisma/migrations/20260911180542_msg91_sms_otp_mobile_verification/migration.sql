-- --- Non-superuser application role grant ------------------------------------
-- No DELETE — a row is superseded (upserted) on resend, never removed by
-- application code.
GRANT SELECT, INSERT, UPDATE ON "mobile_verifications" TO app_user;

-- --- Row Level Security ------------------------------------------------------
-- Every access to this table happens pre-authentication (send-verification,
-- verify-mobile, and registerStudent's own token lookup all run with no
-- real user session) — the same auth_service system-actor identity already
-- established for categories/departments pre-auth reads
-- (20260906150000_student_self_registration/migration.sql). No other
-- legitimate access path exists, so a single FOR ALL policy is sufficient
-- (mirroring payment_service_payment_attempts's own single-policy shape,
-- 20260906200000_payment_attempts/migration.sql).
ALTER TABLE "mobile_verifications" ENABLE ROW LEVEL SECURITY;

CREATE POLICY "auth_service_mobile_verifications" ON "mobile_verifications"
  FOR ALL
  USING (current_setting('app.current_system_actor', true) = 'auth_service')
  WITH CHECK (current_setting('app.current_system_actor', true) = 'auth_service');
